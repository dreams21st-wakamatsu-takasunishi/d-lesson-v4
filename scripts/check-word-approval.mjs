import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { WORD_STAGES } from '../src/data/constants.js';

const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const sql = read('supabase/sql/word_teacher_approval.sql');
const api = read('src/api/word-approval.js');
const word = read('src/games/word.js');
const globals = read('src/app/global-functions.js');
const edge = read('supabase/functions/approve-word-stage/index.ts');
const dialog = read('src/ui/word-approval-dialog.js');
const ids = [...sql.match(/v_stages text\[\] := array\[([^\]]+)\]/)[1].matchAll(/'([^']+)'/g)].map(match => match[1]);
assert.deepEqual(ids, WORD_STAGES.map(stage => stage.id), 'SQL stage order must match the Word menu');
assert.match(sql, /for update/);
assert.match(sql, /primary key \(data_table, user_data_id, stage_id\)/);
assert.match(sql, /revoke all on function public.approve_lesson_word[^;]+from public, anon, authenticated/);
assert.match(sql, /a.auth_user_id = p_actor/);
assert.match(sql, /cleanup_lesson_word_approvals after delete/);
assert.match(edge, /auth.getUser\(token\)/);
assert.match(edge, /p_actor: auth.user.id/);
assert.match(api, /persistSession: false, autoRefreshToken: false, detectSessionInUrl: false/);
assert.match(api, /signOut\(\{ scope: 'local' \}\)/);
assert.doesNotMatch(api, /localStorage|sessionStorage|SERVICE_ROLE/);
assert.match(dialog, /textContent = studentName/);
assert.match(dialog, /passwordInput.value = ''/);
assert.match(dialog, /if \(busy \|\| !form.reportValidity\(\)\) return/);
assert.doesNotMatch(globals, /processWordClear/);
assert.doesNotMatch(word, /u.coins\s*=/);
assert.match(word, /isGuestMode\(\)/);
assert.match(word, /await saveUsers\(false\)/);
console.log('Word approval guards, session isolation, stage parity and storage checks passed.');
