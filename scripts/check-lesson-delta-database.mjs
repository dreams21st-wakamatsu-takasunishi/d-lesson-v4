import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {delimiter,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createLessonDeltaWriter} from '../src/api/lesson-delta.js';
const runtime=(process.env.PATH||'').split(delimiter).map(path=>resolve(path,'..','@electric-sql/pglite/dist/index.js')).find(existsSync);
if(!runtime)throw Error('Run with npm exec --package=@electric-sql/pglite');
const {PGlite}=await import(pathToFileURL(runtime).href),db=new PGlite();
const sql=name=>readFileSync(new URL('../supabase/sql/'+name,import.meta.url),'utf8');
const a='11111111-1111-4111-8111-111111111111',t='22222222-2222-4222-8222-222222222222';
const setActor=id=>db.query("select set_config('test.actor',$1,false)",[id]);
try{
 await db.exec(`create role anon;create role authenticated;create schema auth;
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.actor',true),'')::uuid$$;
 create table lesson_user_access(auth_user_id uuid,role text,user_data_id text);
 create table user_data(id text primary key,data jsonb);
 create table test_user_data(like user_data including all);
 grant usage on schema auth to authenticated;
 grant select on lesson_user_access to authenticated;grant select,update on user_data to authenticated;
 alter table user_data enable row level security;
 create policy visible on user_data to authenticated using(id='student_a');
 insert into lesson_user_access values('${a}','student','student_a'),('${t}','teacher','teacher');
 insert into user_data values('student_a','{"coins":5,"examRecords":{"k":1},"legacy":true,"practiceLogs":[{"id":"latest"},{"id":"past"}]}'),('student_b','{"private":true}');
 `);
 await db.exec(sql('lesson_student_delta.sql'));await db.exec(sql('lesson_staff_roster.sql'));
 const snapshot=async id=>(await db.query("select read_own_lesson_snapshot('user_data',$1) as v",[id])).rows[0].v;
 const writes=[];
 const patch=async(revision,data,removed)=>{
   writes.push({data,removed});
   return (await db.query("select patch_own_lesson_snapshot('user_data','student_a',$1,$2,$3) as v",[revision,data,removed])).rows[0].v;
 };
 await db.exec('set role anon');await assert.rejects(()=>snapshot('student_a'),e=>e.code==='42501');
 await db.exec('set role authenticated');await setActor(a);
 await assert.rejects(()=>snapshot('student_b'),e=>e.code==='42501');
 await assert.rejects(()=>db.query("select * from read_lesson_staff_roster('user_data')"),e=>e.code==='42501');
 const original=await snapshot('student_a'), writer=createLessonDeltaWriter(original.revision,original.data,patch);
 const edited={...original.data,coins:7};delete edited.legacy;
 await Promise.all([writer(edited),writer({...edited,coins:8})]);
 assert.deepEqual(writes,[{data:{coins:7},removed:['legacy']},{data:{coins:8},removed:[]}]);
 assert.deepEqual((await snapshot('student_a')).data,{...edited,coins:8});
 await db.exec("update user_data set data=data||'{\"coins\":25}' where id='student_a'");
 await assert.rejects(()=>writer({...edited,coins:9}),e=>e.code==='PT409');
 assert.equal((await snapshot('student_a')).data.coins,25);
 await setActor(t);await assert.rejects(()=>snapshot('student_a'),e=>e.code==='42501');
 const roster=(await db.query("select * from read_lesson_staff_roster('user_data')")).rows;
 assert.deepEqual(roster.map(r=>r.id),['student_a']);assert.deepEqual(roster[0].data.practiceLogs,[{id:'latest'}]);
 await db.exec('reset role');
 assert.deepEqual((await db.query("select data->'practiceLogs' as v from user_data where id='student_a'")).rows[0].v,[{id:'latest'},{id:'past'}]);
 console.log('Lesson deltas and staff roster: RLS, no lost fields, serial revisions, stale conflict and summary isolation passed');
}finally{await db.close();}
