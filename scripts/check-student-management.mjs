import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseCampusRegistry,registrationCampuses,nextStudentNumber,expectedFields,studentState,describeStudentAccount} from '../src/utils/student-management.js';
const rows=parseCampusRegistry([{id:'main',name:'本校',code:'main',registration_enabled:false},{id:'school',name:'架空校',code:'school'},{id:'other',name:'別校',code:'other',active:false}]);
assert.deepEqual(registrationCampuses(rows,[{role:'admin'}]).map(r=>r.id),['school']);
assert.deepEqual(registrationCampuses(rows,[{role:'teacher',scope_type:'campus',scope_value:'main'}]),[]);
assert.deepEqual(registrationCampuses(rows,[{role:'teacher',scope_type:'campus_group',scope_value:'school:A'}]).map(r=>r.id),['school']);
assert.deepEqual(registrationCampuses(rows,[{role:'student'}]),[]);
assert.throws(()=>parseCampusRegistry([...rows,{id:'main',name:'重複',code:'x'}]));
assert.equal(nextStudentNumber({a:{campusId:'school',loginNumber:'01'},b:{campusId:'other',loginNumber:'2'}},'school'), '2');
assert.deepEqual(expectedFields({group:'A',coins:99},{group:'B',studentState:'paused'}),{group:'A',studentState:null});
assert.equal(studentState({}),'active');
assert.match(describeStudentAccount({authUserId:'set',loginNumber:'1'}),/未検証/);
assert.equal(describeStudentAccount({authUserId:'set'},{loginReady:true,campusReady:false}),'校舎設定を確認');
const sql=readFileSync('supabase/sql/student_management.sql','utf8');
assert.match(sql,/for update/); assert.match(sql,/p_expected/);
assert.match(sql,/data=data \|\| \$2/); assert.match(sql,/revoke all on function public.patch_lesson_login_fields.*authenticated/);
assert.doesNotMatch(sql,/delete from|update public\.user_data set|update auth\.users/i);
console.log('Student management helpers and migration safety checks passed.');
