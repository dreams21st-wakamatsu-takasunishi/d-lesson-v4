import assert from 'node:assert/strict';
import {parseContentItem,parseContentCatalog,replaceCampusCatalogs,campusLearningSettings} from '../src/utils/managed-content.js';
import {getTextProgress} from '../src/utils/standard-route.js';
const old={id:'tt_old',title:'旧課題',content:'{漢字|かんじ}\nあいうえお',time:3,star:2};
const text=parseContentItem('textTasks',old);
const catalog=parseContentCatalog({textTasks:[old],customThemes:[],customEffects:[]});
assert.equal(text.id,old.id);assert.equal(text.content,old.content);assert.equal(text.hidden,false);assert.equal(text.targetGroup,'');
const global={textTasks:[{...old,id:'tt_global'}],globalMistakes:{otherSetting:true}};
replaceCampusCatalogs([{campus_id:'school-a',content:catalog},{campus_id:'school-b',content:{...catalog,textTasks:[]}}]);
const user={campusId:'school-a',textRecords:{tt_old:{score:50}}};
assert.equal(campusLearningSettings(user,global).textTasks[0].id,'tt_old');
assert.equal(getTextProgress(user,global).done,1);
assert.equal(getTextProgress({campusId:'school-b'},global).total,0);
assert.equal(campusLearningSettings({campusId:'public'},global),global);
assert.equal(campusLearningSettings({campusId:'school-a',isMaster:true},global),global);
assert.equal(campusLearningSettings(user,global).globalMistakes.otherSetting,true);
assert.equal(global.textTasks[0].id,'tt_global');
for(const patch of [{time:0},{star:6},{content:''},{hidden:'false'},{id:'<script>'}])assert.throws(()=>parseContentItem('textTasks',{...old,...patch}));
assert.throws(()=>parseContentCatalog({...catalog,textTasks:[old,old]}));
assert.throws(()=>parseContentItem('customThemes',{id:'ct_test',name:'bad',bg:'url(x)',text:'#ffffff',btnBg:'#ffffff',btnText:'#ffffff'}));
replaceCampusCatalogs();assert.equal(campusLearningSettings(user,global),global);
